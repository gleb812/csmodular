// editor/saveService.js
//
// Единая точка сохранения модуля из редактора.
// Убирает дублирование между Toolbar._onSave, TerminalPanel._cmdSave
// и legacy ModulePropertiesWindow.saveModule().
//
// Использование:
//   import { saveModule, sanitizeName } from '../saveService.js';
//   const { lib, name } = await saveModule(app, { lib: 'user' });

/**
 * Санитайз имени модуля (Csound-safe identifier).
 * Пустая строка → '' (вызывающий сам решает, что делать).
 */
export function sanitizeName(raw) {
    let n = String(raw ?? '').replace(/\s/g, '');
    if (/^[0-9]/.test(n)) n = 'M' + n;
    n = n.replace(/[^a-zA-Z0-9_]/g, '');
    return n;
}

/**
 * Сгенерировать JS-описание модуля (export const <Name>Module = {...}).
 * @param {object} m — moduleData
 * @returns {string}
 */
export function generateJsCode(m) {
    const name = m.name || m.originalName || m.type || m.displayName || 'Unknown';
    const componentsJSON = JSON.stringify(m.components, null, 8);
    const list = (arr) => (arr && arr.length) ? `[${arr.join(', ')}]` : '[]';
    const color = m.customColor ? `'${m.customColor}'` : 'null';

    return `// Automatically generated by CsModular Module Editor
export const ${name}Module = {
    type: '${name}',
    defaultParams: [],
    displayName: '${m.displayName || name}',
    category: '${m.category || 'custom'}',
    status: '${m.status || 'dev'}',
    gridHeight: ${m.gridHeight || 3},
    originalName: '${name}',
    tooltip: '${m.displayName || name}',
    customColor: ${color},
    params: ${list(m.params)},
    inputs: ${list(m.inputs)},
    outputs: ${list(m.outputs)},
    components: ${componentsJSON}
};`;
}

/**
 * Собрать moduleData из текущего состояния EditorApp.
 * @param {EditorApp} app
 * @param {string} finalName — уже санитайзенное имя
 * @returns {Promise<object>}
 */
async function _collectModuleData(app, finalName) {
    const { serializeComponents, collectParamIds, collectPorts }
        = await import('./ComponentRegistry.js');

    const components = serializeComponents(app.components);
    const params = collectParamIds(app.components);
    const ports = collectPorts(app.components);

    return {
        name: finalName,
        displayName: finalName,
        type: finalName,
        category: app.module?.category || 'custom',
        status: app.module?.status || 'dev',
        gridHeight: app.module?.gridHeight || 3,
        customColor: app.module?.customColor || null,
        params,
        inputs: ports.inputs,
        outputs: ports.outputs,
        components,
    };
}

/**
 * Сохранить модуль в библиотеку.
 *
 * @param {EditorApp} app
 * @param {object} [opts]
 * @param {string} [opts.lib='user']   — целевая библиотека
 * @param {string} [opts.name=null]    — переопределить имя (иначе app.module.title)
 * @param {boolean} [opts.createLibIfMissing=true] — создать библиотеку, если нет
 * @returns {Promise<{ lib: string, name: string }>}
 */
export async function saveModule(app, opts = {}) {
    const {
        lib = 'user',
        name = null,
        createLibIfMissing = true,
    } = opts;

    const { libraryStore } = await import('../src/api/index.js');

    // 1. Имя
    const rawName = name !== null ? name : (app.module?.title || 'NewModule');
    const finalName = sanitizeName(rawName);
    if (!finalName) {
        throw new Error(`Invalid module name: "${rawName}"`);
    }

    // 2. Библиотека — создаём, если нет (только для user-бэкендов)
    if (createLibIfMissing && lib !== 'user') {
        const libs = await libraryStore.listLibraries();
        const exists = libs.some(l => l.name === lib);
        if (!exists) {
            const ok = await libraryStore.createLibrary(lib, { displayName: lib });
            if (!ok) {
                throw new Error(`Cannot create library "${lib}"`);
            }
        }
    }

    // 3. ⭐ Синхронизация opcode: если имя изменилось — перегенерируем code viewer
    const oldTitle = app.module?.title;
    const needsRename = !!oldTitle && oldTitle !== finalName;
    if (needsRename && app.codeViewerWindow) {
        app.module.title = finalName;
        app.codeViewerWindow.updateCode();
    }

    // 4. Данные
    const moduleData = await _collectModuleData(app, finalName);

    // 5. JS + DSP
    const jsCode = generateJsCode(moduleData);
    let dspCode = null;
    if (app.codeViewerWindow?.getCode) {
        dspCode = app.codeViewerWindow.getCode();
    } else if (app.module?._userCsoundCode) {
        dspCode = app.module._userCsoundCode;
    }

    // 6. ⭐ Safety net: opcode в dspCode должен совпадать с finalName
    if (dspCode) {
        dspCode = _ensureOpcodeName(dspCode, finalName);
    }

    // 7. Запись
    const ok = await libraryStore.saveModule(lib, finalName, jsCode, dspCode);
    if (!ok) {
        // ⭐ Откат переименования при провале
        if (needsRename && app.codeViewerWindow) {
            app.module.title = oldTitle;
            app.codeViewerWindow.updateCode();
        }
        throw new Error(`saveModule("${lib}/${finalName}") returned false`);
    }

    // 8. Синхронизация с app
    if (app.module) {
        app.module.title = finalName;
        app.module.status = moduleData.status;
    }
    app._sourceLibrary = lib;

    return { lib, name: finalName };
}

/**
 * Safety net: убедиться, что opcode в dspCode === name.
 * Основной путь — updateCode() после смены title (шаг 3).
 * Этот — на случай, если codeViewerWindow нет или updateCode() не сработал.
 */
function _ensureOpcodeName(dspCode, name) {
    const re = /^(\s*)opcode\s+([A-Za-z_][A-Za-z0-9_]*)/m;
    const m = dspCode.match(re);
    if (!m) return dspCode;              // нет opcode — не трогаем
    if (m[2] === name) return dspCode;   // уже совпадает
    return dspCode.replace(re, `$1opcode ${name}`);
}