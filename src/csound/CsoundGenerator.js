    async loadUdoContent(typeId) {
        try {
            const response = await fetch(`/csound/modules/${typeId}.txt`);
            if (!response.ok) {
                console.warn(`⚠️ UDO file not found: ${typeId}.txt`);
                return null;
            }
            const content = await response.text();
            return content;
        } catch (error) {
            console.warn(`⚠️ Failed to load UDO: ${typeId}.txt`, error);
            return null;
        }
    }

    /**
     * Загрузить все UDO содержимое для активных модулей
     */
    async loadAllUdoContents() {
        const udoContents = [];
        
        for (const filename of this.includes) {
            // filename = "4.txt", "31.txt" и т.д.
            const typeId = filename.replace('.txt', '');
            const content = await this.loadUdoContent(typeId);
            if (content) {
                udoContents.push(content);
            }
        }
        
        return udoContents;
    }

