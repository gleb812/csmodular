    // ⭐ ВСПОМОГАТЕЛЬНЫЕ МЕТОДЫ ДЛЯ ПАРСИНГА
    _extractDisplayName(code) {
        const match = code.match(/displayName:\s*['"]([^'"]+)['"]/);
        return match ? match[1] : null;
    }

    _extractGridHeight(code) {
        const match = code.match(/gridHeight:\s*(\d+)/);
        return match ? parseInt(match[1]) : null;
    }

    _extractInputs(code) {
        const match = code.match(/inputs:\s*\[([^\]]*)\]/);
        if (!match) return null;
        return match[1].split(',').map(s => parseInt(s.trim())).filter(n => !isNaN(n));
    }

    _extractOutputs(code) {
        const match = code.match(/outputs:\s*\[([^\]]*)\]/);
        if (!match) return null;
        return match[1].split(',').map(s => parseInt(s.trim())).filter(n => !isNaN(n));
    }


